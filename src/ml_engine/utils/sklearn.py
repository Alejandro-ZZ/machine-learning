import logging
from typing import Any, cast, Dict, List, Optional, Tuple


import numpy
from matplotlib.figure import Figure
from numpy.typing import NDArray
from sklearn.metrics import classification_report, jaccard_score, cohen_kappa_score
from statsmodels.stats.proportion import proportion_confint


logger = logging.getLogger("Utils.Sklearn")



def classification_metrics(
        y_true: NDArray, 
        y_pred: NDArray, 
        confidence_level: Optional[float] = 0.95,
        class_names: Optional[List[Any]] = None, 
    ) -> Dict[str, Any]:
    """
    Computes a classification report using scikit-learn's ``classification_report`` function.
    Include additional metrics:

    * ``jaccard``: Jaccard index (IoU) per-class and aggregated (macro, and weighted)
    * ``cohen_kappa``: Cohen's kappa score for inter-rater agreement
    * ``intervals``: Accuracy confidence intervals as a list of [lower_bound, upper_bound]
    

    Notes
    -----
    * Scikit-learn classification report structure::

        {
            "accuracy": <float>,
            "<class_1>": { "f1-score": <float>, "precision": <float>, "recall": <float>, "support": <int> },
            "<class_2>": { ... }, 
            ...
            "macro avg": { "f1-score": <float>, "precision": <float>, "recall": <float>, "support": <int> },
            "weighted avg": { "f1-score": <float>, "precision": <float>, "recall": <float>, "support": <int> }
        }


    Parameters
    ----------
    y_true, y_pred : NDArray
        Ground truth and predicted target values, respectively. 
    
    confidence_level : float, optional
        Level for the accuracy confidence interval (e.g., 0.95 for 95% confidence interval). 
        Computing is based on the Wilson score method trhough ``statsmodels.stats.proportion.proportion_confint``.
        If None (default), confidence intervals will not be computed.
    
    class_names : List[str], optional
        Names of the classes. If None (default), class names will be inferred from the 
        unique values in ``y_true``.
    
    Returns
    -------
    Dict[str, Any]
        A dictionary containing the classification report, additional metrics, and confidence intervals.
    """
    # Handle class names and number of classes
    if class_names is None:
        n_classes = len(numpy.unique(y_true))
        class_names = [str(i) for i in range(n_classes)]
    else:
        n_classes = len(class_names)
        if n_classes != len(numpy.unique(y_true)):
            raise ValueError(f"Number of class names ({n_classes}) does not match number of unique classes in y_true ({len(numpy.unique(y_true))}).")

    # Number of true samples for each class
    class_support = numpy.bincount(y_true)
    
    report: Dict[str, Any] = cast(dict, classification_report(
        y_true=y_true,
        y_pred=y_pred,
        labels=range(n_classes),
        target_names=class_names,
        output_dict=True,
        zero_division=numpy.nan
    ))
    
    # Confidence intervals (Wilson score method) for accuracy
    if confidence_level is not None:
        ci_lower, ci_upper = cast(tuple, proportion_confint(
            count=(y_true == y_pred).sum(),
            nobs=len(y_true),
            alpha=1 - confidence_level,
            method="wilson"
        ))
        report["intervals"] = [float(ci_lower), float(ci_upper)]
        
    # Cohen's kappa score
    cohen_kappa = cohen_kappa_score(y1=y_true, y2=y_pred)
    report["cohen_kappa"] = float(cohen_kappa)
    
    # Jaccard score (IoU) for each class and averages.
    # Mean IoU is the macro average of the Jaccard scores.
    classes_jaccard: NDArray = cast(NDArray, jaccard_score(
        y_true=y_true,
        y_pred=y_pred,
        average=None,
        labels=range(n_classes),
        zero_division=0
    ))

    # Add Jaccard scores to the report
    macro_jaccard = numpy.average(classes_jaccard, weights=None)
    weighted_jaccard = numpy.average(classes_jaccard, weights=class_support)
    report["macro avg"]["jaccard"] = float(macro_jaccard)
    report["weighted avg"]["jaccard"] = float(weighted_jaccard)
    for class_index, class_name in enumerate(class_names):
        report[class_name]["jaccard"] = float(classes_jaccard[class_index])
    
    return report


def display_classification_metrics(
        report: Dict[str, Any], 
        class_names: List[str], 
        average: str = "macro", 
        digits: int = 4, 
        format: str = "grid"
):
    """
    Display two formatted tables for the classification report:

    1. Per-class metrics table
    2. Overall metrics table based on the specified average type ("macro" or "weighted").

    Requires the [tabulate](https://pypi.org/project/tabulate/) library for table formatting.

    Parameters
    ----------
    report : Dict[str, Any]
        The classification report dictionary generated by ``classification_metrics``.
    
    class_names : List[str]
        Names of the classes corresponding to the report.
    
    average : str, optional
        The type of average to display in the overall metrics table.
        Options are "macro" (default) or "weighted".
    
    digits : int, optional
        Number of decimal places to round the metric values for display. Default is 4.
    
    format : str, optional
        The table format for display. 
        Some options are "grid" (default), "plain", "github", "rst", "latex".
    """
    from tabulate import tabulate

    # Prepare per-class metrics table
    per_class_table = []
    for class_name in class_names:
        class_metrics = report[class_name]
        per_class_table.append({
            "Class": class_name,
            "Precision": class_metrics.get("precision", float("nan")),
            "Recall": class_metrics.get("recall", float("nan")),
            "F1-Score": class_metrics.get("f1-score", float("nan")),
            "Support": class_metrics.get("support", float("nan")),
            "Jaccard": class_metrics.get("jaccard", float("nan"))
        })

    # Other overall metric names that are not per-class or average metrics
    other_metrics = {
        name 
        for name in report.keys() 
        if ("avg" not in name) and (name not in class_names)
    }
    
    # Prepare overall metrics table 
    overall_metrics = report[f"{average} avg"]

    # Make table as | metric name | value |
    overall_table = []
    for metric_name in other_metrics.union(overall_metrics.keys()):
        metric_value = overall_metrics.get(metric_name, report.get(metric_name, float("nan")))
        #
        # Format to the specified number of digits
        if isinstance(metric_value, float):
            metric_value = round(metric_value, digits)
        elif isinstance(metric_value, (list, tuple)):
            metric_value = [round(v, digits) for v in metric_value]
        else:
            raise ValueError(f"Unexpected metric value type for '{metric_name}': {type(metric_value)}")
        #
        overall_table.append([ metric_name, metric_value ])

    # Display the tables
    print("\nPer-Class Metrics:")
    print(tabulate(
        per_class_table, 
        headers="keys", 
        tablefmt=format, 
        floatfmt=f".{digits}f"
    ))
    
    print(f"\nOverall Metrics ({average} average):")
    print(tabulate(
        overall_table, 
        headers=["Metric", "Value"], 
        tablefmt=format, 
        # floatfmt=f".{digits}f"
    ))


def plot_classification_metrics(
        report: Dict[str, Any],
        class_names: List[str],
        average: str = "macro",
        title: Optional[str] = None,
        digits: int = 3,
        figsize: Tuple[float, float] = (12, 4.5),
    ) -> Figure:
    """
    Plot a classification report (from ``classification_metrics``) as two bar plot subplots
    sharing the y-axis (metric score), using a minimalist scientific style.

    * Left: per-class grouped bars (f1-score, recall, precision). Recall and precision are
      drawn with transparency to emphasize the f1-score.
    * Right: overall float metrics (``accuracy``, ``cohen_kappa``, and the ``<average> avg`` metrics
      except ``support``). List values (e.g. ``intervals``) are skipped.

    Parameters
    ----------
    report : Dict[str, Any]
        Report returned by ``classification_metrics``.

    class_names : List[str]
        Names of the classes in the report.

    average : str, optional
        Average used for the overall metrics: "macro" (default) or "weighted".

    title : str, optional
        General title of the figure.

    digits : int, optional
        Decimal digits shown in the bar labels. Default is 3.

    figsize : Tuple[float, float], optional
        Figure size in inches.

    Returns
    -------
    Figure
        The matplotlib figure.
    """
    import matplotlib.pyplot as plt
    import pandas
    import seaborn

    per_class_metrics = ["f1-score", "recall", "precision"]
    alphas = {"f1-score": 1.0, "recall": 0.55, "precision": 0.3}

    # Per-class data in long format
    class_df = pandas.DataFrame([
        {"Class": name, "Metric": metric, "Score": float(report[name][metric])}
        for name in class_names
        for metric in per_class_metrics
    ])

    # Overall data: only float values (excludes support and list-valued metrics)
    overall: Dict[str, float] = {}
    for name, value in {**report, **report[f"{average} avg"]}.items():
        if name != "support" and isinstance(value, (float, numpy.floating)):
            overall[name] = float(value)
    overall_df = pandas.DataFrame({"Metric": list(overall.keys()), "Score": list(overall.values())})

    with seaborn.axes_style("ticks"), plt.rc_context({"font.family": "sans-serif"}):
        fig, (ax_class, ax_overall) = plt.subplots(1, 2, figsize=figsize, sharey=True)
        palette = seaborn.color_palette("deep")
        base_color = palette[0]

        seaborn.barplot(
            data=class_df, x="Class", y="Score", hue="Metric", hue_order=per_class_metrics,
            palette={m: base_color for m in per_class_metrics}, ax=ax_class
        )
        # Containers follow hue order; apply alpha per metric and label bars
        for container, metric in zip(ax_class.containers, per_class_metrics):
            for bar in container:  # type: ignore[attr-defined]
                bar.set_alpha(alphas[metric])
            ax_class.bar_label(container, fmt=f"%.{digits}f", padding=2, fontsize=8, rotation=0)  # type: ignore[arg-type]
        legend = ax_class.get_legend()
        if legend is not None:
            legend.remove()
        handles = [
            plt.Rectangle((0, 0), 1, 1, color=base_color, alpha=alphas[m]) for m in per_class_metrics
        ]
        ax_class.legend(
            handles, per_class_metrics, frameon=False, loc="upper center",
            bbox_to_anchor=(0.5, -0.1), ncol=3
        )
        ax_class.set_title("Per-class metrics")
        ax_class.set_xlabel("")
        ax_class.set_ylabel("Score")

        seaborn.barplot(data=overall_df, x="Metric", y="Score", color=palette[1], ax=ax_overall)
        for container in ax_overall.containers:
            ax_overall.bar_label(container, fmt=f"%.{digits}f", padding=2, fontsize=8)  # type: ignore[arg-type]
        ax_overall.set_title(f"Overall metrics ({average} avg)")
        ax_overall.set_xlabel("")
        ax_overall.set_ylabel("")
        ax_overall.tick_params(axis="x", rotation=30)

        # Headroom for labels; remove top and right spines
        ymin = min(0.0, float(min(class_df["Score"].min(), overall_df["Score"].min())))
        ax_class.set_ylim(ymin, 1.15)
        seaborn.despine(fig=fig, top=True, right=True)

        if title:
            fig.suptitle(title, fontweight="bold")
        fig.tight_layout()

    return fig



